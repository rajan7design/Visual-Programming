// Check whether a number is divisible by 5.
 
 using System;
 class Divide
{
    public void Div (int d)
    {
       
        if (d % 5 == 0)
        {
            Console.WriteLine("The number is divisible by 5");
        }
        else
        {
            Console.WriteLine("The number is not divisible by 5");
        }


    }
}